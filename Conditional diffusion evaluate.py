_PRED_RESULTS_ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results_new", "results_RNA")
_PRED_DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")


_PRED_MODELS = None
_PRED_TOKENIZERS = None


def _load_predictor_folds():
    global _PRED_MODELS, _PRED_TOKENIZERS
    if _PRED_MODELS is not None: return
    print("\n[预测模型加载] 仅加载第3折 DNABERT‑2...")
    _PRED_MODELS, _PRED_TOKENIZERS = [], []
    sheet = 'promoter_part3'
    candidates = glob.glob(os.path.join(_PRED_RESULTS_ROOT, f"fold3_{sheet}_*"))
    if not candidates: 
        raise FileNotFoundError(f"找不到fold3_{sheet}模型，请检查路径：{_PRED_RESULTS_ROOT}")
    model_dir = sorted(candidates)[-1]
    with warnings.catch_warnings():
        warnings.filterwarnings(
            "ignore",
            message=r"Unable to import Triton; defaulting MosaicBERT attention implementation to pytorch.*",
            category=UserWarning,
        )
        tok = AutoTokenizer.from_pretrained(model_dir, trust_remote_code=True)
        cfg = BertConfig.from_pretrained(model_dir)
        cfg.num_labels = 1
        m = AutoModelForSequenceClassification.from_pretrained(model_dir, config=cfg, trust_remote_code=True)
    m.to(_PRED_DEVICE).eval()
    _PRED_MODELS.append(m)
    _PRED_TOKENIZERS.append(tok)
    print(f"[预测模型加载] 共加载 {len(_PRED_MODELS)} 个模型（仅fold3）")


def predict_log10(seqs, batch_size=128, max_len=130):
    _load_predictor_folds()
    out = []
    with torch.no_grad():
        for i in range(0, len(seqs), batch_size):
            batch = [str(s).upper() for s in seqs[i:i + batch_size]]

            m, tok = _PRED_MODELS[0], _PRED_TOKENIZERS[0]
            enc = tok(batch, padding=True, truncation=True, max_length=max_len, return_tensors="pt")
            p = m(input_ids=enc["input_ids"].to(_PRED_DEVICE),
                  attention_mask=enc["attention_mask"].to(_PRED_DEVICE)).logits.view(-1).float().cpu().numpy()
            out.append(p)
    return np.concatenate(out)


def detect_actual_frame(seq):
    if len(seq) != 95:
        return -1
    frames_def = {
        0: {'35': 54, '10': 31, 'sd': 14},
        1: {'35': 64, '10': 41, 'sd': 14},
        2: {'35': 74, '10': 51, 'sd': 14},
        3: {'35': 51, '10': 28, 'sd': 11},
        4: {'35': 61, '10': 38, 'sd': 11},
        5: {'35': 71, '10': 48, 'sd': 11},
    }
    P35 = 'TTGACA'
    P10 = 'TATAAT'
    SD = 'AGGAGG'
    for frame_idx, coords in frames_def.items():
        idx_35 = 95 - coords['35']
        idx_10 = 95 - coords['10']
        idx_sd = 95 - coords['sd']
        if (seq[idx_35:idx_35+6] == P35 and
            seq[idx_10:idx_10+6] == P10 and
            seq[idx_sd:idx_sd+6] == SD):
            return frame_idx
    return -1

def check_frame(seq, requested_frame):
    actual = detect_actual_frame(seq)
    return actual == requested_frame


def hamming(s1, s2):
    return sum(c1 != c2 for c1, c2 in zip(s1, s2))


def load_genome_20mers(fasta_path, genome_name="Genome"):
    print(f"\n[基因组比对] 正在加载 {genome_name} 基因组并提取 20-mer...")
    if not os.path.exists(fasta_path):
        raise FileNotFoundError(f"找不到基因组文件: {fasta_path}")
        
    seqs = []
    current_seq = []
    with open(fasta_path, 'r', encoding='utf-8', errors='ignore') as f:
        for line in f:
            line = line.strip()
            if line.startswith('>'):
                if current_seq:
                    seqs.append(''.join(current_seq).upper())
                    current_seq = []
            else:
                current_seq.append(line)
        if current_seq:
            seqs.append(''.join(current_seq).upper())
            
    genome = ''.join(seqs)
    print(f"          -> 成功读取 {len(seqs)} 条序列，总长度: {len(genome)} bp")
    
    kmers = set()
    window = 20
    for i in range(len(genome) - window + 1):
        kmers.add(genome[i:i+window])
        
    print(f"          -> 提取了 {len(kmers)} 个唯一的 20-mer 特征")
    return kmers


def has_homology(seq, kmers, window=20):
    seq = seq.upper()
    if len(seq) < window: return False
    for i in range(len(seq) - window + 1):
        if seq[i:i+window] in kmers:
            return True
    return False


def mark_deduplicate_sequences(df, threshold=0.8):
    print(f"\n[第四步：批内多样性过滤] 正在执行去重 (相似度阈值 >= {threshold*100:.0f}%)...")
    sequences = df['sequence'].tolist()
    keep_indices = []
    dropped_indices = []
    seq_len = 95
    max_diff = int(seq_len * (1 - threshold)) 
    
    for i in tqdm(range(len(sequences)), desc="去重比对进度"):
        seq_i = sequences[i]
        is_duplicate = False
        for j in keep_indices:
            diff_count = sum(1 for a, b in zip(seq_i, sequences[j]) if a != b)
            if diff_count <= max_diff:
                is_duplicate = True
                break
        if is_duplicate:
            dropped_indices.append(i)
        else:
            keep_indices.append(i)
            
    return df.index[dropped_indices] 

def evaluate_generated():
    log_file_path = 'Conditional diffusion/back_evaluation_log.txt'
    os.makedirs(os.path.dirname(log_file_path), exist_ok=True)
    log_file = open(log_file_path, 'w', encoding='utf-8')
    import sys
    class Tee:
        def __init__(self, *files): self.files = files
        def write(self, obj):
            for f in self.files:
                f.write(obj)
                f.flush()
        def flush(self):
            for f in self.files: f.flush()
    original_stdout = sys.stdout
    sys.stdout = Tee(sys.stdout, log_file)

    if not os.path.exists(INPUT_CSV):
        print(f"找不到 {INPUT_CSV}，请等模型生成一些序列后再试。")
        return

    df_gen = pd.read_csv(INPUT_CSV)
    total_raw = len(df_gen)
    print(f"成功加载 {total_raw} 条生成序列。开始安检...\n")
    print("-" * 50)

    df_gen['pass_frame'] = False
    df_gen['actual_frame'] = -1
    df_gen['pass_dup'] = False
    df_gen['pass_gc'] = False
    df_gen['pass_genome'] = False
    df_gen['pass_dedup'] = False
    df_gen['drop_reason'] = ''

    df_train = pd.read_csv(TRAIN_CSV)
    train_seqs = set(df_train['raw_sequence'].tolist())

    df_gen['pass_frame'] = df_gen.apply(lambda row: check_frame(row['sequence'], row['frame']), axis=1)

    df_gen['actual_frame'] = df_gen['sequence'].apply(detect_actual_frame)

    step1_count = df_gen['pass_frame'].sum()
    step1_rate = (step1_count / total_raw) * 100
    print(f"[第一步：排布质控] 骨架完整率: {step1_rate:.1f}% (要求 ≥90%)")
    print(f"         -> 骨架正确保留: {step1_count} 条 (占比: {step1_rate:.1f}%)")
    print("-" * 50)
    
    df_gen.loc[~df_gen['pass_frame'], 'drop_reason'] = '1_Frame_Fail'
    valid_mask = df_gen['pass_frame']

    is_dup_train = df_gen.loc[valid_mask, 'sequence'].isin(train_seqs)
    df_gen.loc[valid_mask, 'pass_dup'] = ~is_dup_train
    step2_count = df_gen['pass_dup'].sum()
    dup_count = is_dup_train.sum()
    step2_rate = (step2_count / total_raw) * 100
    print(f"[第二步：库距离过滤] 与库完全相同: {dup_count} 条")
    print(f"         -> 剔除背题后剩余: {step2_count} 条 (累计占比: {step2_rate:.1f}%)")
    df_gen.loc[valid_mask & is_dup_train, 'drop_reason'] = '2_Duplicate_With_Train'
    valid_mask = valid_mask & df_gen['pass_dup']

    df_gen['gc_content'] = df_gen['sequence'].apply(lambda s: (s.count('G') + s.count('C')) / len(s) if len(s)>0 else 0)
    is_gc_bad = (df_gen['gc_content'] < 0.3) | (df_gen['gc_content'] > 0.7)
    df_gen.loc[valid_mask, 'pass_gc'] = ~is_gc_bad
    gc_bad_count = is_gc_bad.sum()
    step3_count = df_gen['pass_gc'].sum()
    step3_rate = (step3_count / total_raw) * 100
    print(f"[第二步：GC 含量过滤] GC 异常(不在30%-70%): {gc_bad_count} 条")
    print(f"         -> GC 合格剩余: {step3_count} 条 (累计占比: {step3_rate:.1f}%)")
    print("-" * 50)
    df_gen.loc[valid_mask & is_gc_bad, 'drop_reason'] = '3_GC_Out_Of_Range'
    valid_mask = valid_mask & df_gen['pass_gc']

    bs168_kmers = load_genome_20mers(BS168_FASTA, "BS168")
    ecoli_kmers = load_genome_20mers(ECOLI_FASTA, "E. coli K-12")
    print("\n[第三步：基因组同源过滤] 正在比对 20bp 窗口...")
    df_gen['hit_bs168'] = False
    df_gen['hit_ecoli'] = False
    df_gen.loc[valid_mask, 'hit_bs168'] = df_gen.loc[valid_mask, 'sequence'].apply(lambda s: has_homology(s, bs168_kmers))
    df_gen.loc[valid_mask, 'hit_ecoli'] = df_gen.loc[valid_mask, 'sequence'].apply(lambda s: has_homology(s, ecoli_kmers))
    
    is_any_hit = df_gen['hit_bs168'] | df_gen['hit_ecoli']
    df_gen.loc[valid_mask, 'pass_genome'] = ~is_any_hit
    total_hit_count = is_any_hit.sum()
    step4_count = df_gen['pass_genome'].sum()
    step4_rate = (step4_count / total_raw) * 100
    print(f"          -> 总计同源拦截: {total_hit_count} 条")
    print(f"         -> 基因组过滤后剩余: {step4_count} 条 (累计占比: {step4_rate:.1f}%)")
    print("-" * 50)
    df_gen.loc[valid_mask & is_any_hit, 'drop_reason'] = '4_Genome_Homology'
    valid_mask = valid_mask & df_gen['pass_genome']

    if valid_mask.sum() == 0:
        print(" 警告: 经过过滤后，没有序列存活，流程中止。")
        df_gen.to_csv(OUTPUT_CSV, index=False)
        sys.stdout = original_stdout
        log_file.close()
        return

    df_survivors = df_gen[valid_mask].copy()
    dropped_idx = mark_deduplicate_sequences(df_survivors, threshold=0.8)
    
    df_gen['pass_dedup'] = False
    df_gen.loc[valid_mask, 'pass_dedup'] = True
    df_gen.loc[dropped_idx, 'pass_dedup'] = False 
    
    dup_seq_count = len(dropped_idx)
    step5_count = df_gen['pass_dedup'].sum()
    step5_rate = (step5_count / total_raw) * 100
    print(f"          -> 发现高度相似（>=80%）的重复序列: {dup_seq_count} 条")
    print(f"         -> 多样性过滤后剩余: {step5_count} 条 (累计占比: {step5_rate:.1f}%)")
    print("-" * 50)
    df_gen.loc[dropped_idx, 'drop_reason'] = '5_Internal_Deduplication'
    final_valid_mask = valid_mask & df_gen['pass_dedup']

    print("\n正在进行 DNABERT 五折预测 (仅预测最终存活的序列)...")
    df_gen['predicted_log10'] = np.nan
    df_gen['predicted_raw'] = np.nan
    df_gen['predicted_component'] = np.nan
    
    df_final_pass = df_gen[final_valid_mask].copy()
    
    if len(df_final_pass) > 0:
        preds_dnabert = predict_log10(df_final_pass['sequence'].tolist())
        df_final_pass['predicted_log10'] = preds_dnabert
        df_final_pass['predicted_raw'] = 10 ** df_final_pass['predicted_log10']

        def assign_component_by_log10(val):
            comp1_min = _range_df.loc[_range_df['component'] == 1, 'log10_min'].values[0]
            for i in range(1, 10):
                min_v = _range_df.loc[_range_df['component'] == i, 'log10_min'].values[0]
                max_v = _range_df.loc[_range_df['component'] == i, 'log10_max'].values[0]
                if (val >= min_v - 1e-6) and (val <= max_v + 1e-6):
                    return i
            if val > _range_df.loc[_range_df['component'] == 9, 'log10_max'].values[0]:
                return 10

            if val < comp1_min - 1e-6:
                return 0
            return -1


        df_final_pass['predicted_component'] = df_final_pass['predicted_log10'].apply(assign_component_by_log10)
        
        df_gen.loc[final_valid_mask, 'predicted_log10'] = df_final_pass['predicted_log10']
        df_gen.loc[final_valid_mask, 'predicted_raw'] = df_final_pass['predicted_raw']
        df_gen.loc[final_valid_mask, 'predicted_component'] = df_final_pass['predicted_component']

    df_gen.to_csv(OUTPUT_CSV, index=False)
    
    final_count = df_gen['pass_dedup'].sum()
    final_rate = (final_count / total_raw) * 100
    
    print("\n" + "=" * 50)
    print(f" 评估结束！")
    print(f"总计生成 {total_raw} 条 -> 最终存活 {final_count} 条 (总存活率: {final_rate:.1f}%)")
    print(f"完整结果(包含所有未通过的序列及原因)已保存至: {OUTPUT_CSV}")
    print("=" * 50)
    
    match_count = 0
    if final_count > 0:
        print("\n预测落档分布 (仅统计最终存活序列, 1-10箱):")
        print(df_gen.loc[final_valid_mask, 'predicted_component'].value_counts().sort_index())

        target_comp = df_gen.loc[final_valid_mask, 'class'] + 1
        match_count = (target_comp == df_gen.loc[final_valid_mask, 'predicted_component']).sum()
        match_rate = (match_count / final_count) * 100
        print(f"\nDNABERT 预测档位与设定档位完全一致的比例: {match_rate:.1f}%")
        
        print("\n核对样例 (目标档 vs 预测log10 vs 归入档位):")
        sample_check = df_gen.loc[final_valid_mask, ['class', 'predicted_log10', 'predicted_component']].head(5)
        for idx, row in sample_check.iterrows():
            print(f"  目标: {row['class']+1}档 | 预测log10: {row['predicted_log10']:.4f} | 实际归入: {row['predicted_component']}档")

    funnel_data = {
        "Filter Step": ["0. Total Generated", "1. Frame Pass", "2. Non-Duplicate", "3. GC Pass", "4. Genome Pass", "5. Deduplication Pass", "6. Final Survived", "7. Match Target Class"],
        "Count": [total_raw, step1_count, step2_count, step3_count, step4_count, step5_count, final_count, match_count]
    }
    funnel_df = pd.DataFrame(funnel_data)
    funnel_df["Percentage (%)"] = (funnel_df["Count"] / total_raw * 100).round(2)
    funnel_output_path = 'Conditional diffusion/back_evaluation_funnel.xlsx'
    funnel_df.to_excel(funnel_output_path, index=False)
    print(f"\n 漏斗数据已导出至: {funnel_output_path}")
    
    sys.stdout = original_stdout
    log_file.close()
    print(f" 终端日志已完整保存至: {log_file_path}")



if __name__ == '__main__':
    evaluate_generated()