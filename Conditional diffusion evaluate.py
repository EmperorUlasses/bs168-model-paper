"""
Evaluation script for promoter sequences generated by conditional diffusion model.
Performs multi‑step quality control: 
promoter frame validation, 
training‑set duplicate removal,
GC‑content filtering, 
genomic homology screening, 
intra‑batch near‑duplicate deduplication.
Surviving sequences are fed to pre‑trained DNABERT‑2 for transcriptional activity prediction.
Outputs annotated CSV, 
filtering funnel statistics and runtime log for downstream analysis.
"""
